import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Harness-only Expo bootstrap. Keep committed application source untouched:
 * Release deliberately strips the OAuth override, so this acceptance lane must
 * use Debug. Hide only LogBox's dev overlay, never errors or authentication UI.
 * The original entry still runs unchanged after the explicit E2E flag check. */
export function prepareProofEntry(
	root: string,
	output: string,
	origin: string | undefined,
) {
	if (origin !== "http://127.0.0.1:54831")
		throw new Error("Explicit local E2E origin required");
	if (existsSync(join(root, "signin-proof-entry.js")))
		throw new Error("Proof entry already exists");
	const path = join(root, "package.json");
	const original = readFileSync(path, "utf8");
	const pkg = JSON.parse(original);
	if (typeof pkg.main !== "string" || pkg.main === "./signin-proof-entry.js")
		throw new Error("Expected original Expo entry");
	const source = `// Generated by the E2E harness; not application source.
if (__DEV__ && process.env.EXPO_PUBLIC_SIGNIN_PROOF_ORIGIN === "http://127.0.0.1:54831") {
  require("react-native").LogBox.ignoreAllLogs();
  // Route only the fixture's account endpoints and reserved all-zero tunnel.
  // The app still builds its real PKCE requests and grant Cookie. No credentials
  // or success state are injected, and normal/Release entries never install this.
  const originalFetch = globalThis.fetch.bind(globalThis);
  const fixtureHost = "0".repeat(32) + "-lop.radienthq.com";
  globalThis.fetch = (input, init) => {
    const url = new URL(typeof input === "string" ? input : input.url);
    const session = url.hostname === "api.radienthq.com" && url.pathname.startsWith("/v1/tunnels/session/");
    if (session || url.hostname === fixtureHost) {
      return originalFetch("http://127.0.0.1:54831" + url.pathname + url.search, init);
    }
    return originalFetch(input, init);
  };
}
require(${JSON.stringify(pkg.main)});
`;
	mkdirSync(output, { recursive: true });
	writeFileSync(join(output, "original-package.json"), original);
	writeFileSync(join(output, "signin-proof-entry.js"), source);
	writeFileSync(
		join(output, "entry-sha256.txt"),
		createHash("sha256").update(source).digest("hex"),
	);
	writeFileSync(join(root, "signin-proof-entry.js"), source);
	pkg.main = "./signin-proof-entry.js";
	writeFileSync(path, `${JSON.stringify(pkg, null, 2)}\n`);
	return source;
}
if (process.argv[1]?.endsWith("/prepare-entry.ts")) {
	const output = process.argv[2];
	if (!output) throw new Error("Evidence directory required");
	prepareProofEntry(
		process.cwd(),
		output,
		process.env.EXPO_PUBLIC_SIGNIN_PROOF_ORIGIN,
	);
}
