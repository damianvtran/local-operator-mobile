/**
 * HOSTED INSTALLED-APP PROOF ONLY: job-local edits to the CANDIDATE checkout
 * before its debug proof APK is exported and compiled. Every edit is anchored on
 * exact text and fails closed, so a candidate whose seams moved stops the build
 * instead of producing an APK that proves something else. prepare-app.sh
 * restores the two source files after export; nothing is committed anywhere.
 *
 * 1. `src/testing/team-bridge-fixture.ts`: the candidate's fixture seam is
 *    web-only by design. The job adds ONE Android branch, gated on a define only
 *    this job's export sets, that returns the mock hub's synthetic world on the
 *    adb-reversed loopback port. No real accessor, account or bearer is read.
 * 2. A generated entry (`installed-proof-entry.js`) that hides only LogBox's
 *    dev overlay and logs its marker, then requires the original Expo entry.
 * 3. The generated MainApplication loads the embedded asset (the candidate's
 *    own `embeddedHost`, same as the OAuth callback proof) — no Metro.
 *
 * Usage: node prepare.ts <candidate-root> <evidence-dir>
 */
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export const DEFINE = "EXPO_PUBLIC_ANDROID_INSTALLED_PROOF";
export const PORT = "54832";
export const MARKER = "LOP_INSTALLED_PROOF_FIXTURE_54832";
const SEAM_ANCHOR =
	'export function teamBridgeFixture() {\n\tif (process.env.EXPO_PUBLIC_TEAM_BRIDGE_FIXTURES !== "1") return null;';

/* The viewer seam reads `location.search` once teamBridgeFixture() is
 * non-null, which only web could satisfy before this job's Android branch:
 * opening a thread crashed the proof app (run 44233625482, API 36,
 * "Property 'location' doesn't exist"). Keep it web-only. */
const VIEWER_ANCHOR = "\tif (!teamBridgeFixture()) return null;";
export function patchSeam(source: string): string {
	if (source.split(SEAM_ANCHOR).length !== 2 || source.includes(DEFINE))
		throw new Error("Unexpected Team Bridge fixture seam; stop before export");
	if (source.split(VIEWER_ANCHOR).length !== 2)
		throw new Error("Unexpected viewer fixture gate; stop before export");
	if (!source.includes("import { TEAM_BRIDGE_FIXTURE_TOKEN }"))
		throw new Error("Fixture token import moved; stop before export");
	const branch = `export function teamBridgeFixture() {
	// ${MARKER}: hosted installed-app proof job only (never committed).
	if (process.env.${DEFINE} === "${PORT}" && Platform.OS === "android")
		return {
			world: "populated",
			token: TEAM_BRIDGE_FIXTURE_TOKEN,
			locale: "en" as const,
			scale: "100" as const,
			theme: "light" as const,
			baseUrl: "http://127.0.0.1:${PORT}/mock-hub/populated",
			marker: "${MARKER}",
		};
	if (process.env.EXPO_PUBLIC_TEAM_BRIDGE_FIXTURES !== "1") return null;`;
	return source
		.replace(
			VIEWER_ANCHOR,
			'\tif (!teamBridgeFixture() || typeof location === "undefined") return null;',
		)
		.replace(SEAM_ANCHOR, branch);
}

export function proofEntry(main: string): string {
	return `// Generated by the hosted installed-app proof job; not application source.
if (process.env.${DEFINE} === "${PORT}") {
  require("react-native").LogBox.ignoreAllLogs();
  console.info("${MARKER} entry");
}
require(${JSON.stringify(main)});
`;
}

if (process.argv[1]?.endsWith("/prepare.ts")) {
	const [root, evidence] = process.argv.slice(2);
	if (!root || !evidence)
		throw new Error("usage: prepare.ts <root> <evidence>");
	if (process.env.CI !== "true" || process.env[DEFINE] !== PORT)
		throw new Error("Hosted proof job with its explicit define required");
	mkdirSync(evidence, { recursive: true });
	const seam = join(root, "src/testing/team-bridge-fixture.ts");
	copyFileSync(seam, join(evidence, "team-bridge-fixture.original.ts"));
	writeFileSync(seam, patchSeam(readFileSync(seam, "utf8")));
	copyFileSync(seam, join(evidence, "team-bridge-fixture.proof.ts"));

	const pkgPath = join(root, "package.json");
	const original = readFileSync(pkgPath, "utf8");
	writeFileSync(join(evidence, "package.original.json"), original);
	const pkg = JSON.parse(original);
	if (typeof pkg.main !== "string" || pkg.main.includes("installed-proof"))
		throw new Error("Expected original Expo entry");
	const entry = proofEntry(pkg.main);
	writeFileSync(join(root, "installed-proof-entry.js"), entry);
	writeFileSync(join(evidence, "installed-proof-entry.js"), entry);
	writeFileSync(
		join(evidence, "entry.sha256"),
		createHash("sha256").update(entry).digest("hex"),
	);
	pkg.main = "./installed-proof-entry.js";
	writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

	const { embeddedHost } = (await import(
		pathToFileURL(
			join(root, "scripts/ci/android-oauth-callback-proof/embedded-host.ts"),
		).href
	)) as { embeddedHost: (s: string) => string };
	const hostPath = process.env.PROOF_HOST;
	if (!hostPath)
		throw new Error("PROOF_HOST (generated MainApplication.kt) required");
	writeFileSync(hostPath, embeddedHost(readFileSync(hostPath, "utf8")));
	copyFileSync(hostPath, join(evidence, "MainApplication.embedded.kt"));
}
