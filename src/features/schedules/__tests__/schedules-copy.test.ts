describe("monitor row vocabulary", () => {
	it("passes the wire's state words through and dates only armed rows", () => {
		expect(monitorSlot(monitorRow({ state: "dormant" }))).toBe("dormant");
		expect(monitorSlot(monitorRow({ state: "disabled" }))).toBe("disabled");
		expect(monitorSlot(monitorRow({ state: "expired" }))).toBe("expired");
		/* An unknown word is its own word, never mapped onto a known one. */
		expect(monitorSlot(monitorRow({ state: "hibernating" }))).toBe(
			"hibernating",
		);
		expect(monitorSlot(monitorRow())).toBe("in 4m");
		expect(
			monitorSlot(monitorRow({ due_in_s: -300, next_due_at: NOW - 300_000 })),
		).toBe("5m overdue");
		expect(monitorSlot(monitorRow({ next_due_at: null, due_in_s: null }))).toBe(
			"waiting",
		);
	});

	it("suppresses the slot under a parked or gone entry", () => {
		expect(monitorLineViewFor(monitorRow()).slot).toBe("in 4m");
		/* `monitorLineView` is the suppression's home: the wire keeps sending a
		 *  due clock on a parked row, and the row must not print it. */
		expect(monitorLineViewFor(monitorRow(), true).slot).toBe("");
	});

	it("orders the health tail the way the band does", () => {
		/* An unavailable episode outranks a frozen failure count (the count
		 *  halted when the tool went out of reach). */
		expect(
			monitorTail(
				monitorRow({
					unavailable_since: NOW - 300_000,
					health: "tool unavailable since 16:25 — retrying",
					consecutive_failures: 3,
				}),
			),
		).toBe("tool unavailable since 16:25 — retrying");
		expect(monitorTail(monitorRow({ consecutive_failures: 2 }))).toBe(
			"2 failed",
		);
		expect(
			monitorTail(
				monitorRow({
					health:
						"9 checks, 0 deliveries — nothing has changed (confirm the call observes what you expect)",
				}),
			),
		).toBe(
			"9 checks, 0 deliveries — nothing has changed (confirm the call observes what you expect)",
		);
		expect(monitorTail(monitorRow())).toBeNull();
	});

	it("marks news without calling a parked row attention", () => {
		expect(monitorAlerting(monitorRow())).toBe(false);
		expect(monitorAlerting(monitorRow({ state: "disabled" }))).toBe(true);
		expect(monitorAlerting(monitorRow({ state: "expired" }))).toBe(true);
		expect(monitorAlerting(monitorRow({ unavailable_since: 1 }))).toBe(true);
		expect(monitorAlerting(monitorRow({ consecutive_failures: 1 }))).toBe(true);
		/* Dormant is the parked clause's business, not the attention count's. */
		expect(monitorAlerting(monitorRow({ state: "dormant" }))).toBe(false);
	});

	it("heads a monitor entry with its count, next check, or parked sentence", () => {
		const entry = {
			session_id: "bbbb33334444",
			name: "Portfolio rebalance",
			cwd: "~",
			origin: "",
			updated_at: NOW,
			dormant: false,
			ghost: false,
			next_due_at: NOW + 240_000,
			monitors: [monitorRow()],
		};
		expect(monitorEntryClause(entry, NOW)).toBe("1 monitor · next in 4m");
		expect(monitorEntryClause({ ...entry, dormant: true }, NOW)).toBe(
			PARKED_MONITORS_CLAUSE,
		);
		expect(monitorEntryClause({ ...entry, ghost: true }, NOW)).toBe(
			GONE_MONITORS_CLAUSE,
		);
	});
});

