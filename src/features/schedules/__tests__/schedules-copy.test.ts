/**
 * One monitor row's VIEW, through the entry-level derivation the surface
 * actually reads — suppression included. A helper rather than calling the
 * component, because these tests are about the state machine, and a renderer
 * would make them about React Native.
 */
function monitorLineViewFor(
	row: ScheduleMonitorRow,
	suppressed = false,
): MonitorLineView {
	const [entry] = monitorEntryViews(
		monitorListing({
			entries: [
				{
					session_id: "helper",
					name: "helper",
					cwd: "",
					origin: "",
					updated_at: NOW,
					dormant: suppressed,
					ghost: false,
					next_due_at: NOW,
					monitors: [row],
				},
			],
		}),
		NOW,
	);
	const view = entry?.rows[0];
	if (view === undefined)
		throw new Error("unreachable: the helper seeds one row");
	return view;
}
