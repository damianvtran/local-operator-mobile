describe("wake row vocabulary", () => {
	it("spells the cadence the desktop spells, bounded budget included", () => {
		expect(wakeCadenceWord(null, null)).toBe("once");
		expect(wakeCadenceWord(86_400_000, null)).toBe("every 1d");
		expect(wakeCadenceWord(86_400_000, 3)).toBe("every 1d · 3 left");
		/* A spent budget is named as spent rather than as `0 left`, which would
		 *  promise a fire the schedule cannot make. */
		expect(wakeCadenceWord(86_400_000, 0)).toBe(
			"every 1d · no deliveries left",
		);
	});

	it("says `stale` instead of a clock the supervisor has given up on", () => {
		const stale = wakeRow({
			next_due_at: NOW - 8 * 86_400_000,
			stale: true,
		});
		expect(wakeDueWord(stale, NOW)).toBe("stale");
		expect(wakeDueWord(wakeRow(), NOW)).toBe("in 60m");
	});

	it("drops the due slot on a parked entry and on a spent budget", () => {
		const parked = wakeLineView(wakeRow(), NOW, true);
		expect(parked.due).toBe("");
		/* The cadence is what the work IS and stays true under a park. */
		expect(parked.cadence).toBe("once");

		const spent = wakeLineView(
			wakeRow({ limit: 2, fired_count: 2, every_ms: 60_000 }),
			NOW,
			false,
		);
		expect(spent.due).toBe("");
		expect(spent.cadence).toBe("every 1m · no deliveries left");
	});

	it("keeps a stale row's flag even where the slot carries it", () => {
		const row = wakeLineView(wakeRow({ stale: true }), NOW, false);
		expect(row.stale).toBe(true);
		expect(row.due).toBe("stale");
	});

	it("derives the remaining budget with the backend's own arithmetic", () => {
		/* `remaining` is not on this wire — the row carries `limit` and
		 *  `fired_count` — so the same `max(limit - fired_count, 0)` the harness
		 *  uses (`wake.py::due_while_down`) is the one derivation allowed here. */
		const row = wakeLineView(
			wakeRow({ limit: 5, fired_count: 4, every_ms: 3_600_000 }),
			NOW,
			false,
		);
		expect(row.cadence).toBe("every 1h · 1 left");
	});

	it("clamps a fired-beyond-limit row to the spent word, not a negative count", () => {
		const row = wakeLineView(
			wakeRow({ limit: 1, fired_count: 3, every_ms: 3_600_000 }),
			NOW,
			false,
		);
		expect(row.cadence).toBe("every 1h · no deliveries left");
	});
});

describe("wake entry heads", () => {
	const entry = (overrides = {}) => ({
		session_id: "aaaa11112222",
		name: "Invoices follow-up",
		cwd: "~/work/invoices",
		origin: "",
		updated_at: NOW - 90_000,
		dormant: false,
		ghost: false,
		next_due_at: NOW + 3_600_000,
		schedules: [wakeRow()],
		...overrides,
	});

	it("counts and dates an armed entry", () => {
		/* +3,600 s reads `in 60m`: the CLI's minute band runs to 90 minutes
		 *  (`_format_due`), and the port keeps the band, not a prettier hour. */
		expect(wakeEntryClause(entry(), NOW)).toBe("1 wake · next in 60m");
		expect(
			wakeEntryClause(
				entry({ schedules: [wakeRow(), wakeRow({ id: "w2" })] }),
				NOW,
			),
		).toBe("2 wakes · next in 60m");
	});

	it("replaces count and instant with the parked sentence", () => {
		expect(wakeEntryClause(entry({ dormant: true }), NOW)).toBe(
			PARKED_WAKES_CLAUSE,
		);
	});

	it("gives a ghost its own sentence, not the parked one", () => {
		/* The phone's deliberate split: the desktop collapses `dormant ||
		 *  ghost` into "Parked — wakes resume after its next turn", but a
		 *  conversation that no longer exists has no next turn — the
		 *  supervisor and the CLI treat ghost as the stronger, distinct fact. */
		expect(wakeEntryClause(entry({ ghost: true }), NOW)).toBe(
			GONE_WAKES_CLAUSE,
		);
		expect(GONE_WAKES_CLAUSE).not.toBe(PARKED_WAKES_CLAUSE);
	});

	it("falls back to the count when no instant is knowable", () => {
		expect(wakeEntryClause(entry({ next_due_at: null }), NOW)).toBe("1 wake");
	});
});

