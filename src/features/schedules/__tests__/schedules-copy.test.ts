/* ------------------------------------------------------------- supervisor */

describe("the supervisor sentences", () => {
	it("picks the platform reason before the unverifiable one", () => {
		/* `supported: false` also reports `verifiable: false`, so the order is
		 *  the whole rule: a Linux user must read the platform sentence. */
		expect(supervisorLead(supervisor({ supported: false }))).toContain(
			"not supervised on this platform yet",
		);
		expect(
			supervisorLead(supervisor({ supported: false, verifiable: false })),
		).toContain("not supervised on this platform yet");
	});

	it("does not claim somebody else's silence is a stopped supervisor", () => {
		const line = supervisorLead(supervisor({ verifiable: false }));
		expect(line).toContain("Nothing supervises the wakes below");
		expect(line).not.toContain("not running");
	});

	it("names the installed-but-stopped case, and says nothing when it is fine", () => {
		expect(supervisorLead(supervisor({ running: false }))).toContain(
			"installed but not running",
		);
		expect(supervisorLead(supervisor())).toBe("");
	});

	it("reads an absent verifiable as able to speak", () => {
		expect(
			supervisorFires({ supported: true, running: true, detail: "" }),
		).toBe(true);
		expect(
			supervisorFires({
				supported: true,
				running: true,
				detail: "",
				verifiable: false,
			}),
		).toBe(false);
		expect(
			supervisorFires({
				supported: true,
				running: false,
				detail: "",
				verifiable: true,
			}),
		).toBe(false);
	});
});

