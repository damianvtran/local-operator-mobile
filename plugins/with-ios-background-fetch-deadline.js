// JavaScript, and `expo/config-plugins` rather than `@expo/config-plugins`, for
// the loader reasons recorded at the top of `with-android-release-signing.js`.
const { withAppDelegate } = require("expo/config-plugins");

/**
 * Guarantee that iOS's silent-push fetch completion handler is called, even when
 * no JS ever runs to complete it.
 *
 * WHY. iOS passes `application(_:didReceiveRemoteNotification:fetchCompletionHandler:)`
 * a handler the app must call within about 30 s (Apple's documentation of that
 * method). Expo's `ExpoAppDelegateSubscriberManager` calls it only after EVERY
 * subscriber has called its own, and expo-task-manager's calls its own only when
 * the JS task `local-operator.background-push` reports back. Under the scene
 * lifecycle a terminated app woken by a silent push starts no React Native
 * (expo/expo#52878, agent review R1 M1), so that report never comes, the handler
 * is never called, iOS kills the process at its deadline and counts the miss
 * against the app's background budget, which can throttle later silent pushes.
 * `modules/lop-background-launch` fixes the cause by starting React Native; this
 * is the backstop for any other way the task fails to report (a JS crash, a
 * bundle that never loads), so the handler is ALWAYS called exactly once.
 *
 * WHY THE AppDelegate AND NOT A SUBSCRIBER. A subscriber receives Expo's
 * aggregated handler, which fires only once all subscribers have reported; one
 * subscriber cannot complete the push on another's behalf. Overriding the
 * AppDelegate method wraps the handler iOS itself passed, before Expo's
 * aggregation.
 *
 * THE DEADLINE, 28 s. It must sit ABOVE the JS task's own budget, so that a
 * task that is running normally always reports its real result first:
 * `BUDGET_MS` (`src/notifications/background-clear.ts`) and
 * `OUTBOX_WAKE_BUDGET_MS` (`src/features/session/outbox.ts`) are both 25 s,
 * measured from the task's start. And it must sit BELOW iOS's ~30 s, so the
 * handler is called before iOS gives up. A cold wake that reaches it reports
 * `.noData`, which is what a cold wake reports anyway (`background-push-refresh.ts`:
 * "A cold/locked headless wake remains NoData"). Raise it only with those
 * budgets, never past iOS's limit.
 *
 * REMOVE together with `modules/lop-background-launch` when Expo starts React
 * Native for scene-less launches itself (an upstream fix to expo/expo#52878,
 * expected in SDK 58 or later) — or keep it as a backstop; it is harmless.
 *
 * ORDERING. `ios.enableSceneSupport` (expo-build-properties) rewrites the class
 * declaration line. The anchor below matches the declaration with or without
 * its `ExpoReactNativeFactoryProvider` conformance, so mod order does not matter.
 * `scripts/ci/native-config.ts ios-app-delegate` asserts the GENERATED AppDelegate
 * carries the override, so a template change that drops it fails CI.
 */

/** Marker the CI check looks for in the generated AppDelegate. */
const MARKER = "lop-background-fetch-deadline";
const DEADLINE_SECONDS = 28;

const CLASS_DECLARATION =
	/^([ \t]*(?:public[ \t]+)?class AppDelegate: ExpoAppDelegate\b[^{\n]*\{[ \t]*\r?\n)/m;
const EXISTING_OVERRIDE = /didReceiveRemoteNotification userInfo/;

const OVERRIDE = `
  // ${MARKER}: guarantees the silent-push fetch completion handler is called
  // exactly once, within ${DEADLINE_SECONDS} s. Generated by
  // plugins/with-ios-background-fetch-deadline.js, which records why.
  public override func application(
    _ application: UIApplication,
    didReceiveRemoteNotification userInfo: [AnyHashable: Any],
    fetchCompletionHandler completionHandler: @escaping (UIBackgroundFetchResult) -> Void
  ) {
    // A reference box rather than a captured \`var\`: Dispatch's closures are
    // @Sendable, which rejects mutating a captured local. Every read and write
    // is on the main queue, so the flag needs no lock.
    final class Once { var done = false }
    let once = Once()
    let completeOnce: (UIBackgroundFetchResult) -> Void = { result in
      DispatchQueue.main.async {
        guard !once.done else { return }
        once.done = true
        completionHandler(result)
      }
    }
    DispatchQueue.main.asyncAfter(deadline: .now() + ${DEADLINE_SECONDS}) {
      if !once.done {
        NSLog("[${MARKER}] no task result after ${DEADLINE_SECONDS} s; completing with noData")
      }
      completeOnce(.noData)
    }
    super.application(application, didReceiveRemoteNotification: userInfo, fetchCompletionHandler: completeOnce)
  }

`;

/**
 * Pure transform of the AppDelegate.swift source, exported so a unit test can
 * drive it on the SDK 57 template without running prebuild.
 *
 * @param {string} contents
 */
const applyFetchDeadline = (contents) => {
	if (contents.includes(MARKER)) return contents;
	if (EXISTING_OVERRIDE.test(contents)) {
		// Two overrides would not compile; a second owner of this method has to
		// be merged by hand, so fail the prebuild rather than guess.
		throw new Error(
			"with-ios-background-fetch-deadline: AppDelegate already overrides didReceiveRemoteNotification",
		);
	}
	if (!CLASS_DECLARATION.test(contents)) {
		throw new Error(
			"with-ios-background-fetch-deadline: expected the Expo SDK 57 Swift AppDelegate (`class AppDelegate: ExpoAppDelegate`)",
		);
	}
	return contents.replace(CLASS_DECLARATION, `$1${OVERRIDE}`);
};

/** @type {import("@expo/config-plugins").ConfigPlugin} */
const withIosBackgroundFetchDeadline = (config) =>
	withAppDelegate(config, (mod) => {
		if (mod.modResults.language !== "swift") {
			throw new Error(
				"with-ios-background-fetch-deadline: expected a Swift AppDelegate",
			);
		}
		mod.modResults.contents = applyFetchDeadline(mod.modResults.contents);
		return mod;
	});

module.exports = withIosBackgroundFetchDeadline;
module.exports.applyFetchDeadline = applyFetchDeadline;
module.exports.MARKER = MARKER;
module.exports.DEADLINE_SECONDS = DEADLINE_SECONDS;
